"""Model-vs-baseline evaluation report (spec 04, Req 6; AC-3).

The acceptance verdict is deliberately conservative: a model "beats" a baseline on a metric only
if the *lower* end of the model's 95% bootstrap CI is above the baseline's point estimate.
"""

import json
import math
from dataclasses import asdict, dataclass, field
from pathlib import Path


@dataclass
class EvalResult:
    name: str                     # "model" or a baseline name
    split: str                    # "compound" | "scaffold"
    metrics: dict[str, float]
    ci: dict[str, tuple[float, float]] = field(default_factory=dict)


@dataclass
class EvalReport:
    title: str
    task: str                                  # "target" | "sensitivity"
    results: list[EvalResult]
    primary: list[str]                         # metrics used for the acceptance verdict
    manifests: dict[str, dict] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    model: str = "model"
    comparisons: list[str] = field(default_factory=list)   # shown, but not part of the AC-3 gate

    def _get(self, name: str, split: str) -> EvalResult | None:
        return next((r for r in self.results if r.name == name and r.split == split), None)

    def beats_baselines(self) -> dict[str, dict[str, dict[str, bool]]]:
        """{split: {baseline: {metric: bool}}}"""
        out: dict = {}
        for split in sorted({r.split for r in self.results}):
            m = self._get(self.model, split)
            if m is None:
                continue
            for b in (r for r in self.results if r.split == split and r.name != self.model):
                out.setdefault(split, {})[b.name] = {
                    k: bool(k in m.ci and k in b.metrics and math.isfinite(b.metrics[k])
                            and m.ci[k][0] > b.metrics[k])
                    for k in self.primary
                }
        return out

    def accepted(self) -> bool:
        """AC-3: on the compound split, beat every trivial baseline on at least one primary metric.
        Comparison models (e.g. logistic regression) are reported but do not gate acceptance."""
        verdict = {b: v for b, v in self.beats_baselines().get("compound", {}).items() if b not in self.comparisons}
        return bool(verdict) and all(any(v.values()) for v in verdict.values())

    def to_markdown(self) -> str:
        metrics = sorted({k for r in self.results for k in r.metrics})
        lines = [f"# {self.title}", "", "Generated by Oncora's evaluation harness. Do not edit by hand.", ""]
        for split in sorted({r.split for r in self.results}):
            rows = [r for r in self.results if r.split == split]
            lines += [f"## {split.capitalize()}-disjoint split", "",
                      "| Metric | " + " | ".join(r.name for r in rows) + " |",
                      "|---|" + "---|" * len(rows)]
            for k in metrics:
                cells = []
                for r in rows:
                    v = r.metrics.get(k)
                    if v is None or (isinstance(v, float) and math.isnan(v)):
                        cells.append("—")
                        continue
                    ci = r.ci.get(k)
                    cell = f"{v:.3f}" if isinstance(v, float) else f"{v:,}"
                    cells.append(f"**{cell}** [{ci[0]:.3f}, {ci[1]:.3f}]" if ci and k in self.primary else
                                 f"{cell} [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else cell)
                lines.append(f"| {k} | " + " | ".join(cells) + " |")
            lines.append("")
        verdict = self.beats_baselines()
        if verdict:
            lines += ["## Acceptance (AC-3)", "",
                      "A model beats a baseline on a metric when its 95% CI lower bound exceeds the "
                      "baseline's point estimate.", ""]
            for split, per_b in verdict.items():
                for b, per_m in per_b.items():
                    tag = " (comparison model, not gating)" if b in self.comparisons else ""
                    lines.append(f"- {split} vs. **{b}**{tag}: " + ", ".join(
                        f"{k} {'✅' if ok else '❌'}" for k, ok in per_m.items()))
            lines += ["", f"**Accepted: {'yes' if self.accepted() else 'no'}**", ""]
        if self.notes:
            lines += ["## Notes", "", *[f"- {n}" for n in self.notes], ""]
        if self.manifests:
            lines += ["## Split manifests", "", "```json", json.dumps(self.manifests, indent=1), "```", ""]
        return "\n".join(lines)

    def to_json(self) -> str:
        d = asdict(self) | {"beats_baselines": self.beats_baselines(), "accepted": self.accepted()}
        return json.dumps(d, indent=1, default=float)

    def save(self, directory: Path, stem: str) -> None:
        directory.mkdir(parents=True, exist_ok=True)
        (directory / f"{stem}.md").write_text(self.to_markdown())
        (directory / f"{stem}.json").write_text(self.to_json())

"""CCLE expression feature-space EDA (spec 01, Req 4.4; DR-7).

Question: how should 19,215 genes be reduced to a compact cell-line feature vector?

Technique notes:
- A data-driven filter (top-k variance, PCA) must be **fit on training cell lines only**
  inside each fold, or test-line information leaks into the features. The numbers here use all
  985 lines and serve only to choose a strategy and size, never a fitted gene list.
- A curated list (the 978 LINCS landmark genes) needs no fitting, so it cannot leak. It is also
  interpretable and links to the LINCS annotations.
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import polars as pl
from sklearn.decomposition import PCA

from oncora.config import DATA_INTERIM, REPORTS, SEED, raw_path
from oncora.data_prep.bridges import read_lincs_tsv
from oncora.eda.common import save_fig, trainable_model_ids

UNEXPRESSED_MEAN = 1.0  # log1p(TPM) < 1  ⇔  TPM < ~1.7


def load_matrix() -> tuple[np.ndarray, pl.DataFrame]:
    genes = pl.read_parquet(DATA_INTERIM / "ccle_genes.parquet")
    ccle = pl.read_parquet(DATA_INTERIM / "ccle_expression.parquet").filter(
        pl.col("model_id").is_in(trainable_model_ids())
    )
    return ccle.select(genes["gene_col"].to_list()).to_numpy(), genes


def landmark_entrez() -> set[int]:
    gi = read_lincs_tsv(raw_path("geneinfo"))
    return set(gi.filter(pl.col("feature_space") == "landmark")["gene_id"].cast(pl.Int64))


def build_report() -> str:
    X, genes = load_matrix()
    sd, mean = X.std(0), X.mean(0)
    lm = landmark_entrez()
    is_lm = genes["entrez_id"].is_in(list(lm)).to_numpy()
    order = np.argsort(-sd, kind="stable")
    pca = PCA(random_state=SEED).fit(X - mean)
    cum = np.cumsum(pca.explained_variance_ratio_)
    n_pc = {q: int(np.searchsorted(cum, q) + 1) for q in (0.5, 0.8, 0.9, 0.95)}

    fig, axes = plt.subplots(1, 2, figsize=(9, 2.8))
    axes[0].hist(sd[~is_lm], bins=80, alpha=0.7, label="all other genes", density=True)
    axes[0].hist(sd[is_lm], bins=80, alpha=0.7, label="LINCS landmark", density=True)
    axes[0].set_xlabel("std of log1p(TPM) across 985 lines")
    axes[0].legend(frameon=False, fontsize=7)
    axes[0].set_yticks([])
    axes[1].plot(np.arange(1, len(cum) + 1), cum)
    for q, k in n_pc.items():
        axes[1].axhline(q, color="grey", lw=0.5, ls=":")
        axes[1].annotate(f"{k} PCs → {q:.0%}", (k, q), fontsize=7, xytext=(5, -10), textcoords="offset points")
    axes[1].set_xlabel("principal components")
    axes[1].set_ylabel("cumulative variance")
    fig_path = save_fig(fig, "ccle_feature_space.png")

    tops = [500, 1000, 2000, 5000]
    lines = [
        "# CCLE feature-space EDA",
        "",
        "Generated by `uv run python -m oncora.eda.features`. Do not edit by hand. Scope: the "
        f"{X.shape[0]:,} trainable cell lines × {X.shape[1]:,} genes (log1p TPM).",
        "",
        f"![feature space]({fig_path})",
        "",
        "## Gene variability",
        "",
        f"- Median per-gene std: {np.median(sd):.3f}; {int((sd == 0).sum())} genes are constant.",
        f"- {int((mean < UNEXPRESSED_MEAN).sum()):,} genes are essentially unexpressed "
        f"(mean log1p TPM < {UNEXPRESSED_MEAN:g}), and {int((sd < 0.5).sum()):,} have std < 0.5.",
        "",
        "## LINCS landmark genes",
        "",
        f"- {len(lm)} landmark genes in `geneinfo.txt`; **{int(is_lm.sum())} are present in CCLE** (matched on Entrez ID).",
        f"- Median std: landmark {np.median(sd[is_lm]):.3f} vs. all genes {np.median(sd):.3f}. "
        "Landmarks are selected for being informative about the rest of the transcriptome, and "
        "are slightly more variable than average.",
        "- Overlap with the most variable genes is small:",
        "",
        "| Top-k by variance | landmark genes inside |",
        "|---|---|",
        *[f"| {k:,} | {int(is_lm[order[:k]].sum())} |" for k in tops],
        "",
        "## Dimensionality (PCA, centered)",
        "",
        "| Variance explained | Principal components |",
        "|---|---|",
        *[f"| {q:.0%} | {k} |" for q, k in n_pc.items()],
        "",
        "Variance is spread out: a few components capture broad lineage structure, but 80% "
        f"needs {n_pc[0.8]} components.",
        "",
        "## Recommendation (decide at the task 6 checkpoint)",
        "",
        "The DSS3 decomposition (`eda_target.md`) shows cell-line identity explains only about "
        "4–5% of sensitivity variance. A compact, low-risk cell-line representation is "
        "therefore preferable to a large one.",
        "",
        f"1. **MVP: the {int(is_lm.sum())} landmark genes, standardized with training-fold "
        "means and stds.** The gene list is fixed in advance, so there is no selection leakage. "
        "It is interpretable, and it keeps the design matrix at ~3k features "
        "(2,058 compound + 978 genes).",
        "2. **Comparison (STRETCH):** the top-2,000 variance genes and the first 50–100 PCs, both "
        "fit inside each training fold. Keep whichever wins on per-compound ρ.",
        "3. Drop constant genes in any data-driven variant.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=REPORTS / "eda_features.md")
    args = ap.parse_args()
    args.out.write_text(build_report())
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()

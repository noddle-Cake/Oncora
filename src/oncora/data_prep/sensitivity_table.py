"""Compound × cell-line sensitivity modeling table (spec 02, Req 4; DR-4).

One row per (compound, cell line), where a compound is a structure (InChIKey), not a pert_id.
Two pert_ids of the same molecule are merged per cell line by median DSS3, because otherwise one
molecule would appear twice and could land on both sides of a split.

Mixed-scale handling (decision D-03): `mixed_scale` is computed per pert_id *before* merging.
Some molecules (e.g. lapatinib) have one mixed-scale and one clean pert_id, and the flag must
survive the merge. `dss3_rescaled` multiplies values ≥ the scale break by 0.01, also before
merging, for the one sensitivity analysis that keeps these compounds. Rows are never dropped
here; spec 06 chooses which to train on.
"""

import argparse
from pathlib import Path

import polars as pl

from oncora.config import (
    DATA_INTERIM,
    DATA_PROCESSED,
    DEMO_HOLDOUT,
    DSS3_RESCALE_FACTOR,
    DSS3_SCALE_BREAK,
    REPORTS,
)
from oncora.data_prep.provenance import assert_table, write_parquet

DSS3 = DATA_INTERIM / "sensitivity.parquet"
COMPOUNDS = DATA_INTERIM / "compound_bridge.parquet"
CELL_LINES = DATA_INTERIM / "cellline_bridge.parquet"
OUT = DATA_PROCESSED / "sensitivity.parquet"
DEMO_OUT = DATA_PROCESSED / "demo_holdout_sensitivity.parquet"


def build_sensitivity(
    dss3: pl.DataFrame,
    compounds: pl.DataFrame,
    expression_lines: list[str],
    *,
    scale_break: float = DSS3_SCALE_BREAK,
    rescale: float = DSS3_RESCALE_FACTOR,
    holdout: dict[str, str] = DEMO_HOLDOUT,
) -> tuple[pl.DataFrame, pl.DataFrame, dict]:
    per_pert = (
        dss3.filter(pl.col("model_id").is_in(expression_lines))
        .join(compounds.select("pert_id", "inchi_key", "connectivity", "canonical_smiles"),
              on="pert_id", how="left")
        .with_columns(
            (pl.col("dss3") >= scale_break).any().over("pert_id").alias("mixed_scale"),
            pl.when(pl.col("dss3") >= scale_break).then(pl.col("dss3") * rescale)
            .otherwise(pl.col("dss3")).alias("dss3_rescaled"),
        )
    )
    if (n_missing := per_pert["inchi_key"].null_count()):
        raise ValueError(f"{n_missing} DSS3 rows have a pert_id without an InChIKey in compound_bridge")

    merged = (
        per_pert.group_by("inchi_key", "model_id")
        .agg(
            pl.col("connectivity").first(),
            pl.col("canonical_smiles").sort().first(),
            pl.col("pert_id").unique().sort().alias("pert_ids"),
            pl.col("dss3").median(),
            pl.col("dss3_rescaled").median(),
            pl.col("mixed_scale").any(),
        )
        .with_columns(pl.col("mixed_scale").any().over("inchi_key"))
        .select("inchi_key", "connectivity", "canonical_smiles", "pert_ids", "model_id",
                "dss3", "dss3_rescaled", "mixed_scale")
        .sort("inchi_key", "model_id")
    )
    is_demo = pl.col("connectivity").is_in(list(holdout))
    demo, table = merged.filter(is_demo), merged.filter(~is_demo)
    assert_table(table, name="sensitivity", required_cols=list(table.columns), min_rows=100_000,
                 max_null_rate={c: 0.0 for c in ("inchi_key", "connectivity", "canonical_smiles", "dss3")},
                 unique_key=["inchi_key", "model_id"])
    stats = {
        "rows_on_expression_lines": per_pert.height,
        "rows_merged_away": per_pert.height - merged.height,
        "multi_pert_compounds": merged.filter(pl.col("pert_ids").list.len() > 1)["inchi_key"].n_unique(),
    }
    return table, demo, stats


def render_report(table: pl.DataFrame, demo: pl.DataFrame, stats: dict) -> str:
    clean = table.filter(~pl.col("mixed_scale"))

    def shape(df):
        return (f"{df.height:,} rows · {df['inchi_key'].n_unique():,} compounds "
                f"({df['connectivity'].n_unique():,} connectivity blocks) · "
                f"{df['model_id'].n_unique():,} cell lines")

    lines = [
        "# Sensitivity modeling table",
        "",
        "Generated by `uv run python -m oncora.data_prep.sensitivity_table`. Do not edit by hand.",
        "",
        "| Set | Shape |",
        "|---|---|",
        f"| full table | {shape(table)} |",
        f"| **headline training set** (`~mixed_scale`, D-03) | **{shape(clean)}** |",
        f"| mixed-scale compounds (excluded from headline) | {table.filter('mixed_scale')['inchi_key'].n_unique()} compounds |",
        f"| demo holdout ({', '.join(DEMO_HOLDOUT.values())}) | {demo.height:,} rows set aside |",
        "",
        f"- {stats['rows_on_expression_lines']:,} DSS3 rows fall on cell lines with CCLE expression. "
        f"Merging pert_ids that share an InChIKey removed {stats['rows_merged_away']:,} rows "
        f"({stats['multi_pert_compounds']} molecules had more than one pert_id).",
        f"- The headline set covers {clean['model_id'].n_unique():,} of {table['model_id'].n_unique():,} "
        "cell lines: the others were measured only for mixed-scale compounds, consistent with "
        "lines that appear only in the original CCLE screen.",
        f"- Headline DSS3: median {clean['dss3'].median():.4f}, max {clean['dss3'].max():.3f}, "
        f"{(clean['dss3'] == 0).mean():.1%} exactly 0.",
        "- `dss3_rescaled` (values ≥ 1 × 0.01, applied per pert_id before merging) supports the "
        "one sensitivity analysis that includes the mixed-scale compounds.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--report", type=Path, default=REPORTS / "sensitivity_table.md")
    args = ap.parse_args()
    lines = pl.read_parquet(CELL_LINES).filter("in_ccle")["model_id"].to_list()
    table, demo, stats = build_sensitivity(pl.read_parquet(DSS3), pl.read_parquet(COMPOUNDS), lines)
    config = {"scale_break": DSS3_SCALE_BREAK, "rescale_factor": DSS3_RESCALE_FACTOR,
              "demo_holdout": DEMO_HOLDOUT}
    sources = [DSS3, COMPOUNDS, CELL_LINES]
    filters = ["cell lines with CCLE expression", "median DSS3 per (inchi_key, model_id)",
               "mixed_scale flagged per pert_id before merge", "demo holdout removed"]
    write_parquet(table, OUT, sources=sources, created_by=__spec__.name, filters=filters, config=config)
    write_parquet(demo, DEMO_OUT, sources=sources, created_by=__spec__.name, config=config)
    args.report.write_text(render_report(table, demo, stats))
    print(f"Wrote {OUT.name}: {table.height:,} rows")


if __name__ == "__main__":
    main()

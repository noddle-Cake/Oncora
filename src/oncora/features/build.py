"""Build the compound feature table for every modeling compound (spec 03, task 2.2).

    uv run python -m oncora.features.build
"""

import argparse
import time
from pathlib import Path

import polars as pl

from oncora.chem.featurize import CompoundFeatureConfig
from oncora.config import DATA_PROCESSED, REPORTS
from oncora.features.compound import featurize_table

OUT = DATA_PROCESSED / "compound_features.parquet"
INPUTS = [
    DATA_PROCESSED / "target_pairs.parquet",
    DATA_PROCESSED / "sensitivity.parquet",
    DATA_PROCESSED / "demo_holdout_targets.parquet",
    DATA_PROCESSED / "demo_holdout_sensitivity.parquet",
]


def modeling_compounds() -> pl.DataFrame:
    frames = [pl.read_parquet(p, columns=["inchi_key", "canonical_smiles"]) for p in INPUTS]
    return pl.concat(frames).unique("inchi_key").sort("inchi_key")


def render_report(table: pl.DataFrame, cfg: CompoundFeatureConfig) -> str:
    ok = table.filter("ok")
    sens = pl.read_parquet(INPUTS[1], columns=["inchi_key"]).unique()
    sens_ok = ok.join(sens, on="inchi_key", how="semi")
    same_key = (ok["std_inchi_key"] == ok["inchi_key"]).sum()
    same_conn = (ok["std_inchi_key"].str.slice(0, 14) == ok["inchi_key"].str.slice(0, 14)).sum()
    std = ok.select("inchi_key", pl.col("std_inchi_key").str.slice(0, 14).alias("std_conn"))
    tp = pl.read_parquet(INPUTS[0], columns=["inchi_key", "connectivity", "target_chembl_id", "label"]).join(std, on="inchi_key")
    spanning = tp.group_by("std_conn").agg(pl.col("connectivity").n_unique().alias("k")).filter(pl.col("k") > 1).height
    dup = tp.group_by("std_conn", "target_chembl_id").agg(pl.len().alias("n"), pl.col("label").n_unique().alias("nl"))
    n_dup, n_conflict = dup.filter(pl.col("n") > 1).height, dup.filter(pl.col("nl") > 1).height
    lines = [
        "# Compound features",
        "",
        "Generated by `uv run python -m oncora.features.build`. Do not edit by hand.",
        "",
        f"Config: ECFP radius {cfg.radius}, {cfg.n_bits} bits + {len(cfg.descriptors)} descriptors "
        f"({', '.join(cfg.descriptors)}); RDKit {cfg.rdkit_version}.",
        "",
        "| | Count |",
        "|---|---|",
        f"| compounds featurized | {table.height:,} |",
        f"| failed (unparseable after standardization) | {table.height - ok.height:,} |",
        f"| descriptor values replaced (non-finite) | {int(ok['n_nonfinite'].sum()):,} |",
        f"| distinct Murcko scaffolds | {ok['scaffold'].n_unique():,} |",
        f"| acyclic (empty scaffold) | {(ok['scaffold'] == '').sum():,} |",
        f"| sensitivity compounds featurized | {sens_ok.height:,} / {sens.height:,} |",
        f"| sensitivity distinct scaffolds | {sens_ok['scaffold'].n_unique():,} |",
        f"| standardized InChIKey = source InChIKey | {same_key:,} ({same_key / ok.height:.1%}) |",
        f"| … same connectivity block | {same_conn:,} ({same_conn / ok.height:.1%}) |",
        "",
        "## Identity after standardization (refines D-01)",
        "",
        f"- {spanning:,} standardized parents span more than one *source* connectivity block, "
        "mostly salt forms registered separately (e.g. a drug and its mesylate). Their features are "
        "identical, so splitting by the source block would leak. **Splits group by the connectivity "
        "block of the standardized parent (`std_inchi_key[:14]`).**",
        f"- {n_dup:,} (standardized parent, target) groups have more than one row in "
        f"`target_pairs`, {n_conflict:,} with conflicting labels: stereoisomers or salt forms "
        "measured separately, with identical achiral features. Spec 05 collapses them before "
        "training (measured beats sampled; label from the median pChEMBL).",
        "",
        "Rows are keyed by the source InChIKey used in the modeling tables. "
        "Where standardization changes the key (salts stripped, charges neutralized, stereo absent "
        "from the source SMILES), the features describe the standardized parent, which is what "
        "the model sees at inference.",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--jobs", type=int, default=None)
    ap.add_argument("--report", type=Path, default=REPORTS / "compound_features.md")
    args = ap.parse_args()
    cfg = CompoundFeatureConfig()
    t = time.time()
    table = featurize_table(modeling_compounds(), cfg, OUT, n_jobs=args.jobs, sources=INPUTS)
    args.report.write_text(render_report(table, cfg))
    print(f"Wrote {OUT.name}: {table.height:,} compounds "
          f"({table.filter(~pl.col('ok')).height} failed) in {time.time() - t:.0f} s")


if __name__ == "__main__":
    main()
